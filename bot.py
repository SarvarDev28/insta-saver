MAX_FAVORITES = 10


def add_favorite(user_id: int, url: str):
    if not r:
        return
    key = f"favorites:{user_id}"
    existing = r.lrange(key, 0, -1)
    if url in existing:
        return
    r.lpush(key, url)
    r.ltrim(key, 0, MAX_FAVORITES - 1)


def get_favorites(user_id: int) -> list:
    if not r:
        return []
    key = f"favorites:{user_id}"
    return r.lrange(key, 0, MAX_FAVORITES - 1)


