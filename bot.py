@app.on_callback_query(filters.regex(r"^findsong\|"))
async def callback_find_song(client, callback: CallbackQuery):
    """🔍 Qo'shiqni topish — videodagi musiqani aniqlab, 5 ta variant berish"""
    msg_id = int(callback.data.split("|")[1])
    uid = callback.from_user.id
    chat_id = callback.message.chat.id
    url = pending_urls.get(msg_id)

    if not url:
        await callback.answer("⚠️", show_alert=True)
        return

    await callback.answer("🔍", show_alert=False)

    # ⚡ CACHE: avval aniqlangan bo'lsa — Shazam/qidiruvsiz darhol variantlarni ko'rsatish
    cached_meta = get_cache(url, "songmeta")
    if cached_meta and cached_meta.get("results"):
        c_query = cached_meta.get("query", "")
        c_results = cached_meta["results"]
        _remember(song_choices, msg_id, c_results)
        _remember(song_query, msg_id, c_query)
        try:
            await callback.message.reply(
                _build_song_list_text(uid, c_query, c_results),
                reply_markup=_build_song_buttons(c_results, msg_id)
            )
        except Exception as e:
            await callback.message.reply(f"❌ `{str(e)[:100]}`")
        return

    status = await callback.message.reply(t(uid, "song_recognizing"))

    try:
        # 1) Qo'shiqni aniqlash
        query, error = await recognize_song(url, chat_id)
        if error:
            if error == "song_not_found":
                await status.edit_text(t(uid, "song_not_found"))
            else:
                await status.edit_text(get_error_text(uid, error))
            return
        if not query:
            await status.edit_text(t(uid, "song_not_found"))
            return

        await status.edit_text(t(uid, "song_recognized", name=_md_escape(query)))

        # 2) SoundCloud'dan 5 ta variant qidirish (server IP'dan ishonchli)
        results, serr = await search_soundcloud_songs(query, limit=5)
        if serr or not results:
            await status.edit_text(t(uid, "song_no_results"))
            return

        # 3) Variantlarni saqlash (xotira + Redis kesh) va tugmalar yasash
        _remember(song_choices, msg_id, results)
        _remember(song_query, msg_id, query)
        set_cache(url, "songmeta", {"query": query, "results": results})

        await status.edit_text(
            _build_song_list_text(uid, query, results),
            reply_markup=_build_song_buttons(results, msg_id)
        )
    except Exception as e:
        await status.edit_text(f"❌ `{str(e)[:100]}`")
    finally:
        cleanup(chat_id)


@app.on_callback_query(filters.regex(r"^song\|"))
async def callback_pick_song(client, callback: CallbackQuery):
    """Tanlangan variantni MP3 qilib yuklab berish (4 ta effekt tugmasi bilan)"""
    parts = callback.data.split("|")
    msg_id = int(parts[1])
    index = int(parts[2])
    uid = callback.from_user.id
    chat_id = callback.message.chat.id

    results = song_choices.get(msg_id)
    if not results or index >= len(results):
        await callback.answer("⚠️", show_alert=True)
        try:
            await callback.message.edit_text(t(uid, "song_expired"))
        except Exception:
            pass
        return

    chosen = results[index]
    sc_url = chosen["url"]
    query = song_query.get(msg_id, "")

    # ⚡ CACHE: avval yuklangan bo'lsa — file_id orqali darhol yuborish
    cached_audio = get_cache(sc_url, "scaudio")
    if cached_audio and cached_audio.get("file_id"):
        try:
            await callback.answer("⚡", show_alert=False)
            c_title = cached_audio.get("title") or chosen.get("title") or query or "Audio"
            await callback.message.reply_audio(
                cached_audio["file_id"],
                caption=f"🎵 {_md_escape(c_title)} | ⚡ keshdan | 🟧 SoundCloud\n@InstaDownloader_uzBot",
                title=c_title,
                reply_markup=_song_fx_markup(msg_id, index)
            )
            return
        except Exception:
            pass  # file_id eskirgan bo'lsa — qaytadan yuklaymiz

    await callback.answer("⬇️", show_alert=False)
    status = await callback.message.reply(t(uid, "song_downloading"))

    try:
        start_time = _time.time()
        files, error, used_index = await download_song_try_all(results, index, query, chat_id)

        if not files:
            await status.edit_text(get_error_text(uid, error) if error else t(uid, "download_error"))
            return

        used = results[used_index] if 0 <= used_index < len(results) else chosen
        used_url = used.get("url") or sc_url
        elapsed = round(_time.time() - start_time, 1)
        title = used.get("title") or query or "Audio"

        for filepath in files:
            ext = filepath.suffix.lower()
            if ext in [".mp3", ".m4a", ".ogg", ".wav", ".opus"]:
                sent = await callback.message.reply_audio(
                    str(filepath),
                    caption=f"🎵 {_md_escape(title)} | ⚡ {elapsed}s | 🟧 SoundCloud\n@InstaDownloader_uzBot",
                    title=title,
                    reply_markup=_song_fx_markup(msg_id, used_index)
                )
                # ⚡ file_id ni keshlash — keyingi safar darhol kelishi uchun
                try:
                    if sent and sent.audio:
                        set_cache(used_url, "scaudio", {"file_id": sent.audio.file_id, "title": title})
                except Exception:
                    pass
            else:
                await callback.message.reply_document(
                    str(filepath),
                    caption=f"🎵 {_md_escape(title)}\n@InstaDownloader_uzBot"
                )

        await status.delete()
    except Exception as e:
        await status.edit_text(f"❌ `{str(e)[:100]}`")
    finally:
        cleanup(chat_id)


@app.on_callback_query(filters.regex(r"^fxsong\|"))
async def callback_song_effect(client, callback: CallbackQuery):
    """Topilgan qo'shiqqa effekt qo'shish — 8D / Slowed / Bass / Reverb (YouTube havoladan)"""
    parts = callback.data.split("|")
    effect_key = parts[1]
    msg_id = int(parts[2])
    index = int(parts[3])
    uid = callback.from_user.id
    chat_id = callback.message.chat.id

    results = song_choices.get(msg_id)
    if not results or index >= len(results):
        await callback.answer(t(uid, "song_expired"), show_alert=True)
        return
    query = song_query.get(msg_id, "")

    effect = AUDIO_EFFECTS.get(effect_key)
    if not effect:
        await callback.answer("⚠️", show_alert=True)
        return

    await callback.answer(f"{effect['name']} qo'shilmoqda...", show_alert=False)
    status = await callback.message.reply(f"{effect['name']} qo'shilmoqda...")

    try:
        # SoundCloud havoladan yuklab (DRM bo'lsa boshqa variantga o'tadi), keyin effekt qo'shamiz.
        files, error, _used = await download_song_try_all(results, index, query, chat_id)
        if not files:
            await status.edit_text(get_error_text(uid, error) if error else t(uid, "download_error"))
            return

        loop = asyncio.get_running_loop()

        def _apply_effect():
            import subprocess
            out_files = []
            for src in files:
                if src.suffix.lower() not in [".mp3", ".m4a", ".ogg", ".wav", ".opus"]:
                    continue
                dst = DOWNLOAD_DIR / f"{chat_id}_songfx_{src.stem}.mp3"
                cmd = [
                    "ffmpeg", "-y", "-i", str(src),
                    "-af", effect["filter"],
                    "-b:a", "192k",
                    str(dst),
                ]
                try:
                    subprocess.run(cmd, check=True,
                                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                    try:
                        src.unlink()
                    except Exception:
                        pass
                    out_files.append(dst)
                except Exception:
                    pass
            return out_files

        fx_files = await loop.run_in_executor(None, _apply_effect)
        if not fx_files:
            await status.edit_text("❌ Effekt qo'shib bo'lmadi.")
            return

        for filepath in fx_files:
            await callback.message.reply_audio(
                str(filepath),
                caption=f"{effect['name']}\n@InstaDownloader_uzBot",
                title=effect["name"]
            )

        await status.delete()
    except Exception as e:
        await status.edit_text(f"❌ `{str(e)[:100]}`")
    finally:
        cleanup(chat_id)


