async def download_video(url: str, chat_id: int):
    output_template = str(DOWNLOAD_DIR / f"{chat_id}_%(title).40s.%(ext)s")
    ydl_opts = {
        "outtmpl": output_template,
        # H.264 (avc) kodekni afzal ko'rish — Telegram telefon pleyeri uchun
        "format": (
            "bestvideo[ext=mp4][vcodec^=avc1]+bestaudio[ext=m4a]/"
            "best[ext=mp4][vcodec^=avc1]/"
            "best[ext=mp4]/best"
        ),
        "merge_output_format": "mp4",
        "quiet": True,
        "no_warnings": True,
        "socket_timeout": 30,
        "postprocessor_args": {
            "merger": ["-c", "copy", "-movflags", "+faststart"]
        },
    }
    if _cookie_path:
        ydl_opts["cookiefile"] = _cookie_path
    return await _execute_download(url, chat_id, ydl_opts)


async def download_photo(url: str, chat_id: int):
    """Rasmni yuklab olish — instaloader orqali"""
    try:
        loop = asyncio.get_running_loop()

        def _download_with_instaloader():
            import instaloader
            import urllib.request

            L = instaloader.Instaloader(quiet=True)
            # Session cookie bilan login (agar mavjud bo'lsa)
            if INSTAGRAM_SESSION:
                try:
                    L.context._session.cookies.set("sessionid", INSTAGRAM_SESSION, domain=".instagram.com")
                    ds_uid = INSTAGRAM_SESSION.split("%3A")[0] if "%3A" in INSTAGRAM_SESSION else ""
                    if ds_uid:
                        L.context._session.cookies.set("ds_user_id", ds_uid, domain=".instagram.com")
                except Exception:
                    pass
            match = re.search(r'/(?:p|reel|reels|tv)/([A-Za-z0-9_-]+)', url)
            if not match:
                return None

            shortcode = match.group(1)
            try:
                post = instaloader.Post.from_shortcode(L.context, shortcode)
            except Exception:
                return None

            downloaded = []

            if post.typename == 'GraphSidecar':
                for i, node in enumerate(post.get_sidecar_nodes()):
                    if not node.is_video:
                        img_url = node.display_url
                        filepath = DOWNLOAD_DIR / f"{chat_id}_photo_{i}.jpg"
                        urllib.request.urlretrieve(img_url, str(filepath))
                        downloaded.append(filepath)
                    else:
                        # Carousel dagi video
                        vid_url = node.video_url
                        filepath = DOWNLOAD_DIR / f"{chat_id}_video_{i}.mp4"
                        urllib.request.urlretrieve(vid_url, str(filepath))
                        downloaded.append(filepath)
            else:
                if not post.is_video:
                    img_url = post.url
                    filepath = DOWNLOAD_DIR / f"{chat_id}_photo_0.jpg"
                    urllib.request.urlretrieve(img_url, str(filepath))
                    downloaded.append(filepath)

            return downloaded

        files = await loop.run_in_executor(None, _download_with_instaloader)

        if files:
            return files, None
        return None, "❌ Rasm topilmadi."

    except Exception as e:
        err = str(e).lower()
        if "private" in err or "login" in err:
            return None, "private"
        return None, f"❌ Yuklab bo'lmadi: `{str(e)[:100]}`"


async def _execute_download(url: str, chat_id: int, ydl_opts: dict):
    try:
        loop = asyncio.get_running_loop()

        def _download():
            with yt_dlp.YoutubeDL(ydl_opts) as ydl:
                ydl.extract_info(url, download=True)

        await loop.run_in_executor(None, _download)

        files = [f for f in DOWNLOAD_DIR.iterdir() if f.name.startswith(f"{chat_id}_")]
        if files:
            return files, None
        return None, "not_found"

    except yt_dlp.utils.DownloadError as e:
        err = str(e).lower()
        if "private" in err:
            return None, "private"
        elif "login" in err or "sign in" in err or "cookie" in err:
            return None, "login"
        elif "not available" in err or "removed" in err:
            return None, "not_found"
        else:
            return None, f"❌ `{str(e)[:120]}`"
    except Exception as e:
        return None, f"❌ `{str(e)[:120]}`"


def cleanup(chat_id: int):
    for f in DOWNLOAD_DIR.iterdir():
        if f.name.startswith(f"{chat_id}_"):
            try:
                f.unlink()
            except Exception:
                pass


def get_error_text(user_id: int, error: str) -> str:
    if error == "private":
        return t(user_id, "private_error")
    elif error == "login":
        return t(user_id, "login_error")
    elif error == "not_found":
        return t(user_id, "not_found_error")
    elif error.startswith("❌"):
        return error
    return t(user_id, "download_error")


async def send_media_files(message, files, caption, uid, msg_id, url):
    """Fayllarni yuborish:
    - Bitta fayl bo'lsa — tugmalar bilan oddiy yuboradi
    - Bir nechta bo'lsa — media group (albom) qilib bittada yuboradi, keyin tugma alohida
    """
    PHOTO_EXTS = {".jpg", ".jpeg", ".png", ".webp"}
    VIDEO_EXTS = {".mp4", ".mov", ".mkv", ".webm"}

    media_files = [f for f in files if f.suffix.lower() in (PHOTO_EXTS | VIDEO_EXTS)]
    other_files = [f for f in files if f.suffix.lower() not in (PHOTO_EXTS | VIDEO_EXTS)]

    # ─── Bir nechta media — ALBOM qilib yuborish ───
    if len(media_files) > 1:
        media_group = []
        for i, filepath in enumerate(media_files[:10]):  # Telegram limit: 10 ta
            ext = filepath.suffix.lower()
            cap = caption if i == 0 else None  # Faqat birinchisida caption
            if ext in PHOTO_EXTS:
                media_group.append(InputMediaPhoto(str(filepath), caption=cap))
            else:
                media_group.append(InputMediaVideo(str(filepath), caption=cap, supports_streaming=True))

        try:
            await message.reply_media_group(media_group)
            # Albomdan keyin tugmalarni alohida xabar bilan yuborish
            has_video = any(f.suffix.lower() in VIDEO_EXTS for f in media_files)
            buttons = [[InlineKeyboardButton(t(uid, "btn_favorite"), callback_data=f"fav|{msg_id}")]]
            if has_video:
                buttons.append([InlineKeyboardButton(t(uid, "btn_find_song"), callback_data=f"findsong|{msg_id}")])
            await message.reply(
                "✅ " + str(len(media_files)) + " ta media yuklandi\n@InstaDownloader_uzBot",
                reply_markup=InlineKeyboardMarkup(buttons)
            )
        except Exception:
            # Albom ishlamasa — bitta-bitta yuborish
            for filepath in media_files:
                ext = filepath.suffix.lower()
                if ext in PHOTO_EXTS:
                    await message.reply_photo(str(filepath), caption=caption)
                else:
                    await message.reply_video(str(filepath), caption=caption, supports_streaming=True)
        # Boshqa fayllar (agar bo'lsa)
        for filepath in other_files:
            await message.reply_document(str(filepath), caption=caption)
        return

    # ─── Bitta media — oddiy yuborish (tugmalar bilan) ───
    for filepath in files:
        ext = filepath.suffix.lower()
        if ext in VIDEO_EXTS:
            try:
                sent = await message.reply_video(
                    str(filepath),
                    caption=caption,
                    supports_streaming=True,
                    reply_markup=InlineKeyboardMarkup([
                        [InlineKeyboardButton(t(uid, "btn_favorite"), callback_data=f"fav|{msg_id}")],
                        [InlineKeyboardButton(t(uid, "btn_find_song"), callback_data=f"findsong|{msg_id}")]
                    ])
                )
                set_cache(url, "video", {"type": "video", "file_id": sent.video.file_id})
            except Exception:
                sent = await message.reply_document(
                    str(filepath),
                    caption=caption,
                    reply_markup=InlineKeyboardMarkup([
                        [InlineKeyboardButton(t(uid, "btn_favorite"), callback_data=f"fav|{msg_id}")],
                        [InlineKeyboardButton(t(uid, "btn_find_song"), callback_data=f"findsong|{msg_id}")]
                    ])
                )
                set_cache(url, "video", {"type": "document", "file_id": sent.document.file_id})
        elif ext in PHOTO_EXTS:
            try:
                sent = await message.reply_photo(
                    str(filepath),
                    caption=caption,
                    reply_markup=InlineKeyboardMarkup([
                        [InlineKeyboardButton(t(uid, "btn_favorite"), callback_data=f"fav|{msg_id}")]
                    ])
                )
                set_cache(url, "photo", {"type": "photo", "file_id": sent.photo.file_id})
            except Exception:
                await message.reply_document(str(filepath), caption=caption)
        else:
            await message.reply_document(str(filepath), caption=caption)


