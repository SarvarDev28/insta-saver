@app.on_message(filters.text & ~filters.command(["start", "help", "stats", "favorites", "lang", "broadcast", "ban", "unban"]))
async def handle_message(client, message: Message):
    user = message.from_user
    uid = user.id
    text = message.text.strip()
    is_group = message.chat.type in [ChatType.GROUP, ChatType.SUPERGROUP]

    # Bloklangan foydalanuvchi tekshirish
    if is_banned(uid):
        if not is_group:
            await message.reply(t(uid, "banned_msg"))
        return

    # Havola aniqlash
    url, platform = extract_any_url(text)

    if is_group:
        if not url:
            return
    else:
        if not url:
            if text.startswith("http"):
                await message.reply(t(uid, "only_insta_tiktok"))
            else:
                await message.reply(t(uid, "send_link"))
            return

    # Kanal obunasi tekshiruvi (faqat shaxsiy chat, CHANNEL_ID sozlangan bo'lsa)
    if not is_group and CHANNEL_ID and not await check_subscription(client, uid):
        await message.reply(t(uid, "subscribe_channel", channel=CHANNEL_ID))
        return

    save_user(uid)

    # Like reaction
    try:
        await app.send_reaction(message.chat.id, message.id, "❤")
    except Exception:
        pass

    # 💾 CACHE TEKSHIRISH — avval yuklangan bo'lsa darhol yuborish
    cached_video = get_cache(url, "video")
    cached_photo = get_cache(url, "photo")

    if cached_video:
        try:
            if cached_video["type"] == "video":
                await message.reply_video(
                    cached_video["file_id"],
                    caption=t(uid, "caption_speed", platform=platform, seconds="0.1"),
                    supports_streaming=True,
                    reply_markup=InlineKeyboardMarkup([
                        [InlineKeyboardButton(t(uid, "btn_favorite"), callback_data=f"fav|{message.id}")],
                        [InlineKeyboardButton(t(uid, "btn_find_song"), callback_data=f"findsong|{message.id}")]
                    ])
                )
            elif cached_video["type"] == "document":
                await message.reply_document(
                    cached_video["file_id"],
                    caption=t(uid, "caption_speed", platform=platform, seconds="0.1"),
                    reply_markup=InlineKeyboardMarkup([
                        [InlineKeyboardButton(t(uid, "btn_favorite"), callback_data=f"fav|{message.id}")],
                        [InlineKeyboardButton(t(uid, "btn_find_song"), callback_data=f"findsong|{message.id}")]
                    ])
                )
            _remember(pending_urls, message.id, url)
            return
        except Exception:
            pass

    if cached_photo:
        try:
            await message.reply_photo(
                cached_photo["file_id"],
                caption=t(uid, "caption_speed", platform=platform, seconds="0.1"),
                reply_markup=InlineKeyboardMarkup([
                    [InlineKeyboardButton(t(uid, "btn_favorite"), callback_data=f"fav|{message.id}")]
                ])
            )
            _remember(pending_urls, message.id, url)
            return
        except Exception:
            pass

    # Vaqtni boshlash (tezlik uchun)
    start_time = _time.time()

    # 📊 Zamonaviy progress bar
    async def show_progress(status_msg, stage):
        stages = [
            ("🔍", "Link tekshirilmoqda", 10),
            ("📡", "Instagram ga ulanilmoqda", 25),
            ("⬇️", "Yuklab olinmoqda", 50),
            ("🔄", "Qayta ishlanmoqda", 75),
            ("📤", "Telegramga yuborilmoqda", 90),
            ("✅", "Tayyor!", 100),
        ]
        if stage >= len(stages):
            stage = len(stages) - 1
        emoji, text_stage, percent = stages[stage]
        filled = int(percent / 10)
        empty = 10 - filled
        bar = "▰" * filled + "▱" * empty
        elapsed = round(_time.time() - start_time, 1)
        progress_text = (
            f"{emoji} **{text_stage}**\n\n"
            f"{bar}  **{percent}%**\n\n"
            f"⏱ {elapsed} soniya"
        )
        try:
            await status_msg.edit_text(progress_text)
        except Exception:
            pass

    status = await message.reply(
        "🔍 **Link tekshirilmoqda**\n\n"
        "▰▱▱▱▱▱▱▱▱▱  **10%**\n\n"
        "⏱ 0.0 soniya"
    )

    await asyncio.sleep(0.3)
    await show_progress(status, 1)

    # VIDEO yuklab olish
    await asyncio.sleep(0.2)
    await show_progress(status, 2)
    files, error = await download_video(url, message.chat.id)

    # Agar video bo'lmasa — rasm sifatida urinib ko'ramiz (faqat Instagram)
    if error and platform == "Instagram":
        err_str = str(error).lower()
        if "no video" in err_str or "not a video" in err_str or "there is no video" in err_str or error == "not_found":
            cleanup(message.chat.id)
            await show_progress(status, 2)
            files, error = await download_photo(url, message.chat.id)

            if error:
                await status.edit_text(get_error_text(uid, error))
                return

            if not files:
                await status.edit_text(t(uid, "download_error"))
                return

            # Tezlik hisoblash
            elapsed = round(_time.time() - start_time, 1)
            caption = t(uid, "caption_speed", platform=platform, seconds=elapsed)
            await show_progress(status, 4)

            try:
                await send_media_files(message, files, caption, uid, message.id, url)
                _remember(pending_urls, message.id, url)
                await status.delete()
            except Exception as e:
                await status.edit_text(f"❌ `{str(e)[:100]}`")
            finally:
                cleanup(message.chat.id)
            return

    if error:
        await status.edit_text(get_error_text(uid, error))
        return

    if not files:
        await status.edit_text(t(uid, "download_error"))
        return

    # Tezlik hisoblash
    await show_progress(status, 3)
    await asyncio.sleep(0.2)
    await show_progress(status, 4)
    elapsed = round(_time.time() - start_time, 1)
    caption = t(uid, "caption_speed", platform=platform, seconds=elapsed)

    try:
        await send_media_files(message, files, caption, uid, message.id, url)
        _remember(pending_urls, message.id, url)
        await status.delete()

    except Exception as e:
        await status.edit_text(f"❌ `{str(e)[:100]}`")
    finally:
        cleanup(message.chat.id)


