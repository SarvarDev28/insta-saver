async def recognize_song(url: str, chat_id: int):
    """IG havoladan qisqa audio bo'lak olib, Shazam orqali qo'shiqni aniqlash.
    Tezlik uchun: to'liq 320kbps MP3 emas, xom audio yuklanadi va faqat
    birinchi ~15 soniya o'qib olinadi. Qaytaradi: (query_str, error)."""
    loop = asyncio.get_running_loop()

    # 1) Xom audio (qayta kodlashsiz) ni tez yuklab olish
    raw_template = str(DOWNLOAD_DIR / f"{chat_id}_recog.%(ext)s")
    ydl_opts = {
        "outtmpl": raw_template,
        "format": "bestaudio/best",
        "quiet": True,
        "no_warnings": True,
        "socket_timeout": 30,
    }
    if _cookie_path:
        ydl_opts["cookiefile"] = _cookie_path

    def _download_raw():
        with yt_dlp.YoutubeDL(ydl_opts) as ydl:
            ydl.extract_info(url, download=True)
        for f in DOWNLOAD_DIR.iterdir():
            if f.name.startswith(f"{chat_id}_recog."):
                return f
        return None

    try:
        audio_file = await loop.run_in_executor(None, _download_raw)
    except yt_dlp.utils.DownloadError as e:
        err = str(e).lower()
        if "private" in err:
            return None, "private"
        if "login" in err or "sign in" in err:
            return None, "login"
        return None, f"❌ `{str(e)[:100]}`"
    except Exception as e:
        return None, f"❌ `{str(e)[:100]}`"

    if not audio_file:
        return None, "not_found"

    # 2) Faqat birinchi ~15 soniyani past sifatli (mono 16kHz) bo'lakka aylantirish
    snippet = DOWNLOAD_DIR / f"{chat_id}_shazam.ogg"

    def _make_snippet():
        import subprocess
        # "-t 15" ni "-i" dan oldin qo'yamiz — ffmpeg faqat 15s kirishni o'qiydi (tezroq)
        cmd = [
            "ffmpeg", "-y", "-t", "15", "-i", str(audio_file),
            "-vn", "-ac", "1", "-ar", "16000",
            str(snippet),
        ]
        try:
            subprocess.run(cmd, check=True,
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            return str(snippet)
        except Exception:
            return str(audio_file)  # bo'lak ajratib bo'lmasa — to'liq audio

    sample_path = await loop.run_in_executor(None, _make_snippet)

    # 3) Shazam orqali aniqlash
    try:
        from shazamio import Shazam
        shazam = Shazam()
        try:
            out = await shazam.recognize(sample_path)  # shazamio >= 0.5
        except (AttributeError, TypeError):
            out = await shazam.recognize_song(sample_path)  # eski versiya

        track = (out or {}).get("track")
        if not track:
            return None, "song_not_found"

        title = (track.get("title") or "").strip()
        artist = (track.get("subtitle") or "").strip()
        if not title:
            return None, "song_not_found"

        query = f"{artist} - {title}" if artist else title
        return query, None
    except ImportError:
        return None, "❌ shazamio o'rnatilmagan."
    except Exception as e:
        return None, f"❌ `{str(e)[:100]}`"


async def search_soundcloud_songs(query: str, limit: int = 5):
    """SoundCloud'dan qo'shiqni qidirib, `limit` ta variant qaytaradi.
    SoundCloud cloud serverlarni bloklamaydi va cookie talab qilmaydi."""
    loop = asyncio.get_running_loop()

    def _search():
        ydl_opts = {
            "quiet": True,
            "no_warnings": True,
            "extract_flat": True,
            "skip_download": True,
            "socket_timeout": 20,
        }
        with yt_dlp.YoutubeDL(ydl_opts) as ydl:
            info = ydl.extract_info(f"scsearch{limit}:{query}", download=False)
        entries = (info or {}).get("entries", []) or []
        results = []
        for e in entries:
            if not e:
                continue
            link = e.get("url") or e.get("webpage_url")
            results.append({
                "title": e.get("title") or "Audio",
                "url": link,
                "duration": e.get("duration"),
                "uploader": e.get("uploader") or e.get("uploader_id") or "",
            })
        return [x for x in results if x["url"]]

    try:
        return await loop.run_in_executor(None, _search), None
    except Exception as e:
        return [], f"❌ `{str(e)[:100]}`"


async def download_audio_from_url(url: str, chat_id: int):
    """Berilgan havoladan (SoundCloud va h.k.) to'g'ridan-to'g'ri MP3 (192kbps) yuklab olish.
    SoundCloud bepul treklari ~128kbps, shuning uchun 192 yetarli va tezroq."""
    output_template = str(DOWNLOAD_DIR / f"{chat_id}_song_%(title).40s.%(ext)s")
    ydl_opts = {
        "outtmpl": output_template,
        "format": "bestaudio/best",
        "quiet": True,
        "no_warnings": True,
        "socket_timeout": 30,
        "postprocessors": [{
            "key": "FFmpegExtractAudio",
            "preferredcodec": "mp3",
            "preferredquality": "192",
        }],
    }

    for f in DOWNLOAD_DIR.iterdir():
        if f.name.startswith(f"{chat_id}_song_"):
            try:
                f.unlink()
            except Exception:
                pass

    try:
        loop = asyncio.get_running_loop()

        def _download():
            with yt_dlp.YoutubeDL(ydl_opts) as ydl:
                ydl.extract_info(url, download=True)

        await loop.run_in_executor(None, _download)
        files = [f for f in DOWNLOAD_DIR.iterdir()
                 if f.name.startswith(f"{chat_id}_song_")]
        if files:
            return files, None
        return None, "not_found"
    except Exception as e:
        return None, f"❌ `{str(e)[:120]}`"


async def download_song_try_all(results: list, start_index: int, query: str, chat_id: int):
    """Tanlangan variantdan boshlab, yuklab bo'ladiganini topguncha urinadi.
    Ba'zi SoundCloud treklari DRM bilan himoyalangan — ular o'tkazib yuboriladi.
    Qaytaradi: (files, error, used_index)."""
    n = len(results)
    order = [start_index] + [i for i in range(n) if i != start_index]
    last_error = None
    for idx in order:
        url = results[idx].get("url") if 0 <= idx < n else None
        if not url:
            continue
        files, error = await download_audio_from_url(url, chat_id)
        if files:
            return files, None, idx
        last_error = error
    # Hech qaysi variant ishlamasa — nom bo'yicha qayta qidirib ko'ramiz
    if query:
        files, error = await download_song_from_soundcloud(query, chat_id)
        if files:
            return files, None, start_index
        last_error = error or last_error
    return None, last_error, start_index


