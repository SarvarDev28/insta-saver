COOKIE_FILE = Path("instagram_cookies.txt")

def _create_cookie_file():
    """Instagram session cookie ni Netscape formatda fayl qilib yaratish"""
    if not INSTAGRAM_SESSION:
        return None
    # sessionid dan ds_user_id ajratish (format: userid%3Atoken...)
    ds_user_id = ""
    try:
        ds_user_id = INSTAGRAM_SESSION.split("%3A")[0]
    except Exception:
        pass
    cookie_content = (
        "# Netscape HTTP Cookie File\n"
        "# https://curl.haxx.se/rfc/cookie_spec.html\n"
        "# This file was generated by bot\n\n"
        f".instagram.com\tTRUE\t/\tTRUE\t0\tsessionid\t{INSTAGRAM_SESSION}\n"
    )
    if ds_user_id:
        cookie_content += f".instagram.com\tTRUE\t/\tTRUE\t0\tds_user_id\t{ds_user_id}\n"
    COOKIE_FILE.write_text(cookie_content)
    return str(COOKIE_FILE)

# Bot ishga tushganda cookie yaratish
