def _format_duration(seconds) -> str:
    """Sekundni mm:ss ko'rinishiga keltirish"""
    try:
        seconds = int(seconds)
        return f"{seconds // 60}:{seconds % 60:02d}"
    except Exception:
        return ""


def _build_song_list_text(uid: int, query: str, results: list) -> str:
    """Variantlarni raqamlangan matn ro'yxati — har biri bitta qatorda.
    Nom va query Markdown'ni buzmasligi uchun escape qilinadi."""
    lines = [t(uid, "song_choose", name=_md_escape(query)), ""]
    for i, res in enumerate(results, 1):
        dur = _format_duration(res.get("duration"))
        title = _md_escape((res.get("title") or "Audio").replace("\n", " ").strip()[:45])
        line = f"**{i}.** {title}"
        if dur:
            line += f" • {dur}"
        lines.append(line)
    return "\n".join(lines)


def _build_song_buttons(results: list, msg_id: int) -> InlineKeyboardMarkup:
    """Faqat raqamli tugmalar (1 2 3 4 5) — bitta qatorda"""
    row = [
        InlineKeyboardButton(str(i + 1), callback_data=f"song|{msg_id}|{i}")
        for i in range(len(results))
    ]
    return InlineKeyboardMarkup([row])


